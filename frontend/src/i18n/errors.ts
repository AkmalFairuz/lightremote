export function localizedApiMessage(code: string | undefined, message: string | undefined): string {
  const key = code ? errorKeys[code] : undefined
  if (!key) return message ? translateMessage(message) : t('common.theRequestCouldNotBeCompleted')
  const summary = t(key)
  // Fixed API messages use translated summaries; opaque diagnostics retain their detail.
  if (message && !knownApiMessages.has(message)) {
    return `${summary}\n${translateMessage(message)}`
  }
  return summary
}
